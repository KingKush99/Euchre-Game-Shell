export interface ThemeItem {
  id: number;
  themeKey: string;
  title: string;
  category: 'main_menu' | 'profile' | 'in_game';
  index: number; // 0 to 9 within category
  badge: string;
  costCoins: number;
  unlocked: boolean;
  bgGradient: string;
  patternStyle: string;
  imagePrompt: string;
  previewEmoji: string;
  imageUrl?: string;
  // Specific visual styling properties
  accentColor: string;
  borderClass: string;
  textGlow: string;
  feltColorHex?: number;
  rimColorHex?: number;
  bgHex?: number;
}

/**
 * Pricing logic:
 * First 3 (index 0, 1, 2) = Free (0 coins)
 * 4th (index 3) = 100 coins
 * 5th (index 4) = 200 coins
 * 6th (index 5) = 400 coins
 * 7th (index 6) = 800 coins
 * 8th (index 7) = 1,600 coins
 * 9th (index 8) = 3,200 coins
 * 10th (index 9) = 6,400 coins
 */
export function getThemePrice(index: number): { cost: number; badge: string } {
  if (index < 3) {
    return { cost: 0, badge: 'FREE' };
  }
  const cost = 100 * Math.pow(2, index - 3);
  return {
    cost,
    badge: `${cost.toLocaleString()} coins`,
  };
}

